final allManagersProvider = StreamProvider<List<ManagerEntity>>((ref) {
  final ds = ref.watch(workerManagerDatasourceProvider);
  return ds.watchAllManagers();
});

final allWorkersProvider = StreamProvider<List<WorkerEntity>>((ref) {
  final ds = ref.watch(workerManagerDatasourceProvider);
  return ds.watchAllWorkers();
});

final workerManagerControllerProvider =
    StateNotifierProvider<WorkerManagerController, AsyncValue<void>>((ref) {
  return WorkerManagerController(ref);
});

class WorkerManagerController extends StateNotifier<AsyncValue<void>> {
  final Ref _ref;

  WorkerManagerController(this._ref) : super(const AsyncValue.data(null));

  WorkerManagerDatasource get _datasource =>
      _ref.read(workerManagerDatasourceProvider);

  /// One-time password reset link (24h) for a manager, worker or client.
  /// Returns null (and sets the error state) on failure.
  Future<String?> createResetLink(String userId) async {
    try {
      return await _datasource.createPasswordResetLink(userId);
    } catch (e, st) {
      state = AsyncValue.error(e, st);
      return null;
    }
  }

  Future<bool> addWorker({
    required String name,
    required String username,
    required String password,
    String? phone,
    String? trade,
    String? assignToProjectId,
  }) async {
    state = const AsyncValue.loading();
    try {
      final assignedProjects =
          assignToProjectId != null ? [assignToProjectId] : <String>[];

      final worker = WorkerModel(
        id: '', // ID will be generated by Firestore
        name: name,
        phone: phone ?? '',
        trade: trade ?? '',
        password: password,
        assignedProjects: assignedProjects,
        username: username,
      );

      // 1. Create Create Worker
      final workerId = await _datasource.addWorker(worker);

      // 2. If project ID is provided, update the project's workerIds
      if (assignToProjectId != null) {
        final projectDs = _ref.read(projectDatasourceProvider);
        final project = await projectDs.getProjectById(assignToProjectId);
        await projectDs.updateProject(assignToProjectId, {
          'workerIds': {...project.workerIds, workerId}.toList(),
        });
      }

      state = const AsyncValue.data(null);
      return true;
    } catch (e, st) {
      state = AsyncValue.error(e, st);
      return false;
    }
  }

  // ─── Manager CRUD ──────────────────────────────────────────────────────

  Future<bool> addManager({
    required String name,
    required String password,
    String phone = '',
    String email = '',
  }) async {
    state = const AsyncValue.loading();
    try {
      final manager = ManagerModel(
        id: '',
        name: name,
        phone: phone,
        email: email,
        password: password,
        isSuspended: false,
        assignedProjects: const [],
      );
      await _datasource.addManager(manager);
      state = const AsyncValue.data(null);
      return true;
    } catch (e, st) {
      state = AsyncValue.error(e, st);
      return false;
    }
  }

  /// Passwords are not editable any more; use [createResetLink].
  Future<bool> updateManager({
    required String managerId,
    required String name,
    required bool isSuspended,
    String phone = '',
    String email = '',
  }) async {
    state = const AsyncValue.loading();
    try {
      await _datasource.updateManager(managerId, {
        'name': name,
        'phone': phone,
        'email': email,
        'isSuspended': isSuspended,
      });
      state = const AsyncValue.data(null);
      return true;
    } catch (e, st) {
      state = AsyncValue.error(e, st);
      return false;
    }
  }

  Future<bool> deleteManager(String managerId) async {
    state = const AsyncValue.loading();
    try {
      await _datasource.deleteManager(managerId);
      state = const AsyncValue.data(null);
      return true;
    } catch (e, st) {
      state = AsyncValue.error(e, st);
      return false;
    }
  }

  // ─── Worker CRUD ──────────────────────────────────────────────────────

  Future<bool> updateWorker({
    required String workerId,
    required String name,
    String? username,
    String phone = '',
    String trade = '',
  }) async {
    state = const AsyncValue.loading();
    try {
      await _datasource.updateWorker(workerId, {
        'name': name,
        'phone': phone,
        'trade': trade,
        if (username != null && username.trim().isNotEmpty) 'username': username.trim().toLowerCase(),
      });
      state = const AsyncValue.data(null);
      return true;
    } catch (e, st) {
      state = AsyncValue.error(e, st);
      return false;
    }
  }

  Future<bool> deleteWorker(String workerId) async {
    state = const AsyncValue.loading();
    try {
      await _datasource.deleteWorker(workerId);
      state = const AsyncValue.data(null);
      return true;
    } catch (e, st) {
      state = AsyncValue.error(e, st);
      return false;
    }
  }
}

/// Provider that enriches each manager with their assigned project details
final managerWithProjectsProvider =
    Provider.family<AsyncValue<List<ProjectEntity>>, List<String>>((ref, projectIds) {
  if (projectIds.isEmpty) return const AsyncValue.data([]);
  
  // We use the allProjects stream from project_providers and filter
  final allProjectsAsync = ref.watch(allProjectsProvider);
  return allProjectsAsync.when(
    data: (projects) {
      final matching = projects.where((p) => projectIds.contains(p.id)).toList();
      return AsyncValue.data(matching);
    },
    loading: () => const AsyncValue.loading(),
    error: (e, st) => AsyncValue.error(e, st),
  );
});
